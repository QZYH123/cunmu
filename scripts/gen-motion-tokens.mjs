#!/usr/bin/env node
/**
 * tokens.css is the one source of the motion values (MOTION-SPEC §5): this writes src/motion.gen.ts from its
 * --m-* durations, --e-* curves and --stagger, plus the reduced duration from the reduced-motion block.
 * `node scripts/gen-motion-tokens.mjs` writes it; `--check` exits 1 when the file is out of date (check-spec #76).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = join(ROOT, 'src/motion.gen.ts');

export function motionTokens(css) {
  const t = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const root = t.match(/:root\s*\{([\s\S]*?)\n\}/)[1];
  const red = t.match(/:root\[data-motion="reduce"\]\s*\{([\s\S]*?)\n\}/)[1];
  const ms = (block, k) => { const m = block.match(new RegExp(`--${k}:\\s*(\\d+)ms`)); if (!m) throw new Error(`--${k} missing`); return +m[1]; };
  const ease = (k) => { const m = root.match(new RegExp(`--e-${k}:\\s*([^;]+);`)); if (!m) throw new Error(`--e-${k} missing`); return m[1].trim(); };
  const M = Object.fromEntries(['instant', 'quick', 'base', 'space', 'sign', 'sheen', 'tint'].map((k) => [k, ms(root, `m-${k}`)]));
  M.reduced = ms(red, 'm-base');
  const E = Object.fromEntries(['out', 'move', 'in', 'settle'].map((k) => [k, ease(k)]));
  return { M, E, stagger: ms(root, 'stagger') };
}

export function render({ M, E, stagger }) {
  return `// Generated by scripts/gen-motion-tokens.mjs from src/styles/tokens.css — do not edit; change tokens.css.
/** --m-* durations in ms (reduced: --m-base under data-motion="reduce") */
export const M = ${JSON.stringify(M).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ').replace(/\{/, '{ ').replace(/\}$/, ' }')} as const;
/** --e-* curves */
export const E = {
${Object.entries(E).map(([k, v]) => `  ${k === 'in' ? "'in'" : k}: '${v}',`).join('\n')}
} as const;
/** --stagger in ms */
export const STAGGER = ${stagger};
`;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const want = render(motionTokens(readFileSync(join(ROOT, 'src/styles/tokens.css'), 'utf8')));
  if (process.argv.includes('--check')) {
    let have = ''; try { have = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (have !== want) { console.error('src/motion.gen.ts is out of date: run node scripts/gen-motion-tokens.mjs'); process.exit(1); }
  } else writeFileSync(OUT, want);
}
