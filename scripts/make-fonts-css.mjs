#!/usr/bin/env node
/**
 * src/styles/noto-serif-sc.css from fontsource's Noto Serif SC 500 / 600 CSS:
 *   - woff2 only (every WebView the app runs in reads it; fontsource also lists a woff copy of every slice,
 *     which doubled the fonts in the APK)
 *   - only the unicode-range slices that hold at least one GB 2312 character (the common simplified set);
 *     the rest are emoji, private-use and symbol slices the system fonts draw anyway
 * Each slice still loads only when a page uses a character in it. Run after updating @fontsource/noto-serif-sc.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const PKG = '@fontsource/noto-serif-sc';
const gb = new Set();
const dec = new TextDecoder('gb18030');
for (let a = 0xa1; a <= 0xf7; a++) for (let b = 0xa1; b <= 0xfe; b++) {
  const ch = dec.decode(new Uint8Array([a, b]));
  if (ch.length === 1 && ch !== '\ufffd' && !(a >= 0xaa && a <= 0xaf) && !(a >= 0xf8)) gb.add(ch.codePointAt(0));
}
const inRange = (range) => range.split(',').some((part) => {
  const [lo, hi] = part.trim().slice(2).split('-').map((h) => parseInt(h, 16));
  for (let c = lo; c <= (hi ?? lo); c++) if (gb.has(c)) return true;
  return false;
});

let out = `/* Generated by scripts/make-fonts-css.mjs from ${PKG} — do not edit. woff2 only; slices with GB 2312 characters. */\n`;
let kept = 0, dropped = 0;
for (const w of [500, 600]) {
  const css = readFileSync(join(ROOT, 'node_modules', PKG, `${w}.css`), 'utf8');
  for (const block of css.match(/@font-face\s*{[^}]*}/g)) {
    const range = block.match(/unicode-range:\s*([^;]+);/)?.[1];
    if (range && !inRange(range)) { dropped++; continue; }
    kept++;
    out += block
      .replace(/src:[^;]+;/, (src) => src.replace(/,\s*url\([^)]*\.woff\)\s*format\(['"]woff['"]\)/, ''))
      .replace(/url\(\.\/files\//g, `url('${PKG}/files/`).replace(/\.woff2\)/g, ".woff2')") + '\n';
  }
}
writeFileSync(join(ROOT, 'src/styles/noto-serif-sc.css'), out);
console.log(`noto-serif-sc.css: ${kept} slices kept, ${dropped} dropped`);
